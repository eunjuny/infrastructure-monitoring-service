import { afterEach, beforeAll, describe, expect, it, vi } from 'vitest'
import { mount, flushPromises, type VueWrapper } from '@vue/test-utils'
import App from '../src/App.vue'
import { api, ApiError, type Detail } from '../src/api'
import { deferred, page, resource } from './fixtures'
let wrapper: VueWrapper | undefined
beforeAll(async () => { await import('../src/components/ResourceDetail.vue') })
afterEach(() => { wrapper?.unmount(); wrapper = undefined })
function setup() {
  const cluster = resource(1, 'CLUSTER'), node = resource(1, 'NODE'), namespace = resource(1, 'NAMESPACE'), pod = resource(1)
  const summary = vi.spyOn(api, 'summary').mockResolvedValue({ clusters: 20, nodes: 200, namespaces: 2000, pods: 100000 })
  const list = vi.spyOn(api, 'list').mockResolvedValue(page([{ resource: pod, path: [] }]))
  const detail = vi.spyOn(api, 'detail').mockImplementation(async r => ({ resource: r.type === 'POD' ? pod : r.type === 'NODE' ? node : r.type === 'NAMESPACE' ? namespace : cluster,
    path: r.type === 'POD' ? [cluster, node, namespace, pod] : r.type === 'NODE' ? [cluster, node] : [cluster], attributes: r.type === 'NODE' ? { cpuUsage: 17, memoryUsage: 23 } : { restartCount: 1 } }))
  const children = vi.spyOn(api, 'children').mockImplementation(async parent => page(!parent ? [cluster] : parent.type === 'CLUSTER' ? [node] : parent.type === 'NODE' ? [namespace] : [pod]))
  wrapper = mount(App)
  return { cluster, node, namespace, pod, summary, list, detail, children }
}
const button = (text: string) => wrapper!.findAll('button').find(b => b.text() === text)!
describe('screen to API connection', () => {
  it('uses navigation shortcuts and summary cards to request the selected type', async () => {
    const { list } = setup(); await flushPromises()
    await wrapper!.findAll('.resource-navigation button')[1]!.trigger('click'); await flushPromises()
    expect(list.mock.calls.at(-1)![0]).toEqual({ type: 'NODE', q: '', status: '', parentId: undefined })
    await wrapper!.find('button[aria-label="Namespace 전체 목록 보기"]').trigger('click'); await flushPromises()
    expect(list.mock.calls.at(-1)![0].type).toBe('NAMESPACE')
  })
  it('labels status counts as current window counts rather than full database totals', async () => {
    setup(); await flushPromises()
    expect(wrapper!.find('.window-statuses').text()).toContain('현재 조회창')
    expect(wrapper!.find('.window-statuses').text()).toContain('전체 DB 집계 아님')
    expect(wrapper!.find('.normal-text').text()).toContain('정상 1')
    expect(wrapper!.findAll('.resource-row .parent-cell')).toHaveLength(1)
    expect(wrapper!.find('.resource-row time').attributes('datetime')).toBe('2026-10-13T00:00:00Z')
  })
  it('uses fixed local timestamps without initializing locale formatters in the first screen', async () => {
    const localeFormat = vi.spyOn(Date.prototype, 'toLocaleString')
    const formatter = vi.spyOn(Intl, 'DateTimeFormat')
    const numberLocale = vi.spyOn(Number.prototype, 'toLocaleString')
    setup(); await flushPromises()
    expect(wrapper!.find('.resource-row time').attributes('title')).toMatch(/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:00$/)
    expect(formatter).not.toHaveBeenCalled()
    expect(numberLocale).not.toHaveBeenCalled()
    expect(localeFormat).not.toHaveBeenCalled()
    await wrapper!.find('button[aria-label="Node 전체 목록 보기"]').trigger('click'); await flushPromises()
    expect(localeFormat).not.toHaveBeenCalled()
  })
  it('closes selected details and prevents a pending response from reopening them', async () => {
    const { detail } = setup(); await flushPromises()
    const pending = deferred<Detail>(); detail.mockReturnValueOnce(pending.promise)
    await wrapper!.find('.resource-row').trigger('click')
    await flushPromises()
    await wrapper!.find('button[aria-label="상세 닫기"]').trigger('click')
    pending.resolve({ resource: resource(), path: [], attributes: {} }); await flushPromises()
    expect(wrapper!.find('.detail-panel').exists()).toBe(false)
    expect(wrapper!.find('.resource-row.selected').exists()).toBe(false)
  })
  it('switches detail tabs and navigates the typed relationship cards', async () => {
    setup(); await flushPromises()
    await wrapper!.find('.resource-row').trigger('click'); await flushPromises()
    await wrapper!.find('#path-tab').trigger('click')
    expect(wrapper!.find('#path-tab').attributes('aria-selected')).toBe('true')
    expect(wrapper!.find('#path-panel').isVisible()).toBe(true)
    expect(wrapper!.find('#overview-panel').isVisible()).toBe(false)
    expect(wrapper!.findAll('.relationship-cards button')).toHaveLength(4)
    await wrapper!.findAll('.relationship-cards button')[1]!.trigger('click'); await flushPromises()
    expect(wrapper!.find('.detail-panel h3').text()).toBe('node-1')
  })
  it('shows Node percentages as real server-derived meter values', async () => {
    setup(); await flushPromises()
    await wrapper!.find('button[aria-label="cluster-1 펼치기"]').trigger('click'); await flushPromises()
    await wrapper!.findAll('.tree-name').find(node => node.text() === 'node-1')!.trigger('click'); await flushPromises()
    expect(wrapper!.findAll('meter').map(meter => meter.attributes('value'))).toEqual(['17', '23'])
  })
  it('supports slash to focus search, escape to close detail, and leaves typing alone', async () => {
    setup(); await flushPromises()
    await wrapper!.find('.resource-row').trigger('click'); await flushPromises()
    window.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' })); await wrapper!.vm.$nextTick()
    expect(wrapper!.find('.detail-panel').exists()).toBe(false)
    const focus = vi.spyOn(wrapper!.find('.filters input').element as HTMLElement, 'focus')
    window.dispatchEvent(new KeyboardEvent('keydown', { key: '/', cancelable: true }))
    expect(focus).toHaveBeenCalledTimes(1)
    await wrapper!.find('.filters input').trigger('keydown', { key: '/' })
    expect(focus).toHaveBeenCalledTimes(1)
  })
  it('polls the current window without repeatedly querying aggregate counts', async () => {
    vi.useFakeTimers()
    const { list, summary } = setup(); await flushPromises()
    await vi.advanceTimersByTimeAsync(5000); await flushPromises()
    expect(list).toHaveBeenCalledTimes(2); expect(summary).toHaveBeenCalledTimes(1)
    await wrapper!.find('input[type="checkbox"]').setValue(false)
    await vi.advanceTimersByTimeAsync(60000)
    expect(list).toHaveBeenCalledTimes(2); expect(wrapper!.text()).toContain('수동 갱신 모드')
  })
  it('initially loads summary, root hierarchy and global Pod page only', async () => {
    const { children, list } = setup(); await flushPromises()
    expect(wrapper!.text()).toContain('100,000')
    expect(list).toHaveBeenCalledWith({ type: 'POD', q: '', status: '', parentId: undefined }, null, expect.any(AbortSignal))
    expect(children).toHaveBeenCalledTimes(1)
    expect(children.mock.calls[0]![0]).toBe(null)
    expect(wrapper!.findAll('.resource-row')).toHaveLength(1)
  })
  it('lazily expands/collapses a branch without reloading cached children', async () => {
    const { children } = setup(); await flushPromises()
    await wrapper!.find('button[aria-label="cluster-1 펼치기"]').trigger('click'); await flushPromises()
    expect(wrapper!.find('.tree-panel').text()).toContain('node-1')
    await wrapper!.find('button[aria-label="cluster-1 접기"]').trigger('click')
    expect(wrapper!.find('.tree-panel').text()).not.toContain('node-1')
    await wrapper!.find('button[aria-label="cluster-1 펼치기"]').trigger('click'); await flushPromises()
    expect(children).toHaveBeenCalledTimes(2)
  })
  it('shows server detail, restart count and clickable full path', async () => {
    setup(); await flushPromises()
    await wrapper!.find('.resource-row').trigger('click'); await flushPromises()
    expect(wrapper!.find('.detail-panel').text()).toContain('재시작 횟수')
    expect(wrapper!.findAll('.breadcrumbs button').map(b => b.text())).toEqual(['cluster-1', 'node-1', 'namespace-1', 'pod-1'])
    await wrapper!.findAll('.breadcrumbs button')[1]!.trigger('click'); await flushPromises()
    expect(wrapper!.find('.detail-panel').text()).toContain('CPU 사용률 (%)')
    expect(wrapper!.find('.detail-panel').text()).toContain('17')
  })
  it('browses a selected parent using the correct child type and parent ID', async () => {
    const { list } = setup(); await flushPromises()
    await wrapper!.find('button[aria-label="cluster-1 하위 목록 보기"]').trigger('click'); await flushPromises()
    expect(list.mock.calls.at(-1)![0]).toEqual({ type: 'NODE', parentId: 1, status: '', q: '' })
    expect(wrapper!.find('#list-heading').text()).toBe('cluster-1 하위 목록')
  })
  it('debounces search and invalidates old rows immediately', async () => {
    const { list, cluster, node, namespace, pod } = setup(); await flushPromises()
    vi.useFakeTimers()
    list.mockResolvedValue(page([{ resource: pod, path: [cluster, node, namespace, pod] }]))
    await wrapper!.find('.filters input').setValue('pod-1')
    expect(wrapper!.findAll('.resource-row')).toHaveLength(0)
    expect(list).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(250); await flushPromises()
    expect(list.mock.calls.at(-1)![0].q).toBe('pod-1')
    expect(wrapper!.find('.resource-row').text()).toContain('cluster-1 / node-1 / namespace-1 / pod-1')
  })
  it('supports global search across types and status filters', async () => {
    const { list } = setup(); await flushPromises()
    await wrapper!.find('.filters input').setValue('pod')
    await wrapper!.findAll('.filters select')[0]!.setValue('')
    await wrapper!.findAll('.filters select')[1]!.setValue('ERROR'); await flushPromises()
    expect(list.mock.calls.at(-1)![0]).toEqual({ type: '', parentId: undefined, status: 'ERROR', q: 'pod' })
    await wrapper!.find('.filters input').setValue(''); await wrapper!.find('form').trigger('submit'); await flushPromises()
    expect(list.mock.calls.at(-1)![0].type).toBe('POD')
  })
  it('reveals all ancestors of a selected search match', async () => {
    setup(); await flushPromises()
    await wrapper!.find('.resource-row').trigger('click'); await flushPromises()
    await button('계층에서 위치 보기').trigger('click'); await flushPromises()
    const text = wrapper!.find('.tree-panel').text()
    expect(text).toContain('cluster-1'); expect(text).toContain('node-1'); expect(text).toContain('namespace-1'); expect(text).toContain('pod-1')
    expect(wrapper!.findAll('.tree-item.selected')).toHaveLength(1)
  })
  it('refreshes statuses without clearing selected detail or rows while waiting', async () => {
    const { list, pod } = setup(); await flushPromises()
    await wrapper!.find('.resource-row').trigger('click'); await flushPromises()
    const pending = deferred<Awaited<ReturnType<typeof api.list>>>()
    list.mockReturnValueOnce(pending.promise)
    await button('새로고침').trigger('click')
    expect(wrapper!.find('.resource-row.selected').exists()).toBe(true)
    expect(wrapper!.find('.detail-panel').text()).toContain('pod-1')
    pending.resolve(page([{ resource: { ...pod, status: 'ERROR' }, path: [] }]))
    await flushPromises()
    expect(wrapper!.find('.resource-row .badge').text()).toBe('오류')
    expect(wrapper!.find('.resource-row.selected').exists()).toBe(true)
  })
  it('ignores detail responses from previously selected resources', async () => {
    const { detail, cluster } = setup(); await flushPromises()
    const pending = deferred<Detail>(); detail.mockReturnValueOnce(pending.promise)
    await wrapper!.find('.resource-row').trigger('click')
    await wrapper!.find('.tree-name').trigger('click'); await flushPromises()
    pending.resolve({ resource: resource(999), path: [], attributes: {} }); await flushPromises()
    expect(wrapper!.find('.detail-panel h3').text()).toBe(cluster.name)
  })
  it('shows errors and empty states instead of fabricated data', async () => {
    const { list } = setup(); await flushPromises()
    list.mockRejectedValueOnce(new ApiError(503))
    await wrapper!.find('form').trigger('submit'); await flushPromises()
    expect(wrapper!.find('.list-panel [role="alert"]').text()).toContain('DB')
    list.mockResolvedValueOnce(page([]))
    await wrapper!.find('.list-panel [role="alert"] button').trigger('click'); await flushPromises()
    expect(wrapper!.find('.list-panel').text()).toContain('조건에 맞는 리소스가 없습니다.')
  })
  it('renders API text as text, never executable HTML', async () => {
    const { list, pod } = setup(); await flushPromises()
    list.mockResolvedValueOnce(page([{ resource: { ...pod, name: '<img src=x onerror=alert(1)>' }, path: [] }]))
    await wrapper!.find('form').trigger('submit'); await flushPromises()
    expect(wrapper!.find('.resource-row').text()).toContain('<img src=x onerror=alert(1)>')
    expect(wrapper!.find('img').exists()).toBe(false)
  })
})
